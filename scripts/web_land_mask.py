"""Build the dotted globe's land mask for the web app's Sessions page (``web/src/landmask.ts``).

Source: Natural Earth 1:110m land polygons (public domain), e.g.
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson

The sphere is covered by rows of evenly spaced dots: ``ROWS`` latitude rows of ``STEP`` degrees, row ``i`` at latitude
``-90 + STEP * (i + 0.5)`` with ``max(1, round(360 / STEP * cos(lat)))`` dots at longitudes
``-180 + (j + 0.5) * 360 / n``. One bit per dot (1 = land, even-odd point-in-polygon test), rows concatenated, packed
LSB first and base64-encoded. ``web/src/Globe.tsx`` decodes it with exactly these formulas.

Usage: python scripts/web_land_mask.py <ne_110m_land.geojson> [web/src/landmask.ts]
"""

from __future__ import annotations

import base64
import json
import math
import sys
from pathlib import Path

import numpy as np

STEP = 1.5
ROWS = int(180 / STEP)


def dots() -> tuple[np.ndarray, np.ndarray]:
    lats, lons = [], []
    for i in range(ROWS):
        lat = -90 + STEP * (i + 0.5)
        n = max(1, round(360 / STEP * math.cos(math.radians(lat))))
        for j in range(n):
            lats.append(lat)
            lons.append(-180 + (j + 0.5) * 360 / n)
    return np.array(lats), np.array(lons)


def inside(lat: np.ndarray, lon: np.ndarray, rings: list[list[list[float]]]) -> np.ndarray:
    """Even-odd rule over every ring (outer rings and holes alike), in the plain lon/lat plane."""
    out = np.zeros(len(lat), dtype=bool)
    for ring in rings:
        r = np.asarray(ring, dtype=float)
        x1, y1 = r[:-1, 0], r[:-1, 1]
        x2, y2 = r[1:, 0], r[1:, 1]
        for a, b, c, d in zip(x1, y1, x2, y2, strict=True):
            crosses = (b > lat) != (d > lat)
            with np.errstate(divide="ignore", invalid="ignore"):
                x_at = a + (lat - b) * (c - a) / (d - b)
            out ^= crosses & (lon < x_at)
    return out


def main() -> None:
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "web" / "src" / "landmask.ts"
    lat, lon = dots()
    land = np.zeros(len(lat), dtype=bool)
    for feature in json.loads(src.read_text(encoding="utf-8"))["features"]:
        g = feature["geometry"]
        polygons = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for rings in polygons:
            land |= inside(lat, lon, rings)
    packed = np.packbits(land, bitorder="little").tobytes()
    text = (
        "// Generated by scripts/web_land_mask.py from Natural Earth 1:110m land (public domain) - do not edit by hand.\n"
        f"// {len(lat)} dots in {ROWS} rows of {STEP} degrees, {int(land.sum())} on land; one bit per dot, LSB first.\n"
        f"export const LAND_STEP = {STEP};\n"
        f'export const LAND_BITS = "{base64.b64encode(packed).decode()}";\n'
    )
    dst.write_text(text, encoding="utf-8")
    print(f"{dst}: {len(lat)} dots, {int(land.sum())} land ({land.mean():.1%}), {len(packed)} bytes")


if __name__ == "__main__":
    main()
